DROP TABLE IF EXISTS STUDENT;
CREATE TABLE STUDENT(Id INT PRIMARY KEY,Name VARCHAR(100),Marks INT);
INSERT INTO STUDENT(Id,Name,Marks) VALUES
(1,'Lion',75),
(2,'Tiger',80),
(3,'Dog',50),
(4,'Cat',45);
SELECT * FROM STUDENT;
SELECT AVG(Marks) AS AVG_EXAMPLE FROM STUDENT;
SELECT SUM(Marks) AS SUM_EXAMPLE FROM STUDENT;
SELECT COUNT(*) AS COUNT_EXAMPLE FROM STUDENT;
SELECT COUNT(Name) AS COUNT_EXAMPLE FROM STUDENT;
SELECT MAX(Marks) AS MAX_EXAMPLE FROM STUDENT;
SELECT MIN(Marks) AS MAX_EXAMPLE FROM STUDENT;
SELECT VARIANCE(Marks) AS VAR FROM STUDENT;
SELECT STDDEV(Marks) AS VAR FROM STUDENT;
SELECT STDDEV_POP(Marks) AS VAR FROM STUDENT;