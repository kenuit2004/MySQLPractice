WITH AVERAGE AS(SELECT DEPARTMENT,AVG(SALARY) AS AVERAGE_SALARY FROM STUDENT GROUP BY DEPARTMENT),
RANKING AS(SELECT s.Id,s.Name,s.Department,s.Salary,a.AVERAGE_SALARY,RANK() OVER(PARTITION BY s.DEPARTMENT ORDER BY Salary DESC) AS RANKED_SALARY FROM STUDENT AS s JOIN AVERAGE AS a ON s.DEPARTMENT=a.DEPARTMENT)
SELECT * FROM RANKING;
