DROP TABLE IF EXISTS STUDENT;
CREATE TABLE STUDENT(Id INT PRIMARY KEY,Name VARCHAR(100),Salary INT);
INSERT INTO STUDENT(Id,Name,Salary) VALUES
(1,'Lion',1000),
(2,'Tiger',5000),
(3,'Dog',6000),
(4,'Cat',9000);
WITH AVERAGE AS(SELECT AVG(Salary) AS AVERAGE_SALARY FROM STUDENT) SELECT * FROM STUDENT WHERE Salary>(SELECT AVERAGE_SALARY FROM AVERAGE);
WITH MINIMUM AS(SELECT MIN(SALARY) AS MINIMUM_SALARY FROM STUDENT) SELECT * FROM STUDENT WHERE SALARY=(SELECT MINIMUM_SALARY FROM MINIMUM);
WITH MAXIMUM AS(SELECT MAX(SALARY) AS MAXIMUM_SALARY FROM STUDENT) SELECT * FROM STUDENT WHERE SALARY=(SELECT MAXIMUM_SALARY FROM MAXIMUM);